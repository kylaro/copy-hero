import AppKit

enum ClipContent {
    case text(String)
    case image(NSImage, data: Data, type: NSPasteboard.PasteboardType)
}

struct ClipItem {
    let content: ClipContent
    let date = Date()

    /// Single-line summary shown in the history rows.
    var title: String {
        switch content {
        case .text(let s):
            let collapsed = s.split(whereSeparator: \.isNewline)
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .filter { !$0.isEmpty }
                .joined(separator: " ⏎ ")
            return String(collapsed.prefix(200))
        case .image(let img, _, _):
            return "🖼  Image \(Int(img.size.width))×\(Int(img.size.height))"
        }
    }

    func isSameContent(as other: ClipContent) -> Bool {
        switch (content, other) {
        case (.text(let a), .text(let b)): return a == b
        case (.image(_, let a, _), .image(_, let b, _)): return a == b
        default: return false
        }
    }
}

/// In-memory only. Nothing is ever written to disk.
final class ClipboardHistory {
    static let limit = 20
    private(set) var items: [ClipItem] = []

    func add(_ content: ClipContent) {
        // Re-copying something already in history moves it to the top.
        items.removeAll { $0.isSameContent(as: content) }
        items.insert(ClipItem(content: content), at: 0)
        if items.count > Self.limit {
            items.removeLast(items.count - Self.limit)
        }
    }

    func clear() {
        items.removeAll()
    }
}

/// Polls the general pasteboard for changes (macOS has no copy notification).
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let onCopy: (ClipContent) -> Void

    // Markers set by password managers and other apps that don't want their data recorded.
    // See http://nspasteboard.org
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(onCopy: @escaping (ClipContent) -> Void) {
        self.onCopy = onCopy
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        if let s = pasteboard.string(forType: .string),
           !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            onCopy(.text(s))
            return
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), let img = NSImage(data: data) {
                onCopy(.image(img, data: data, type: type))
                return
            }
        }
    }
}
